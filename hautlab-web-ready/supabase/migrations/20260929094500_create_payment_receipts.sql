    source_reference,
    source_payment_id,
    source_order_id,
    payment_status,
    receipt_status,
    amount,
    currency,
    paid_at,
    payment_method_id,
    payment_type_id,
    installments,
    live_mode,
    test_mode
  ) values (
    'mercado_pago_point',
    new.external_reference,
    coalesce(new.payment_reference_id, new.transaction_id),
    new.mp_order_id,
    new.status,
    v_receipt_status,
    new.amount,
    new.currency,
    coalesce(new.paid_at, new.provider_updated_at, new.updated_at, now()),
