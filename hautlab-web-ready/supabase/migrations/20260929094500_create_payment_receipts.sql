-- Safe backfill for already-verified paid states.
insert into public.payment_receipts (
  source_provider, source_reference, source_payment_id, source_order_id,
  payment_status, receipt_status, amount, currency, paid_at,
  payment_method_id, payment_type_id, live_mode, test_mode
)
select
  'mercado_pago', external_reference, mp_payment_id, preference_id,
  status,
  case when status = 'refunded' then 'refunded'
       when status = 'charged_back' then 'charged_back'
       else 'issued' end,
  amount, currency, coalesce(paid_at, updated_at),
  payment_method_id, payment_type_id, live_mode, test_mode
from public.payment_orders
where status in ('approved', 'refunded', 'charged_back')
on conflict (source_provider, source_reference) do nothing;

insert into public.payment_receipt_items (
  receipt_id, line_no, item_code, label, quantity, unit_price, discount_amount, line_total
)
select r.id, 1, o.product_code, o.product_label, 1, o.amount, 0, o.amount
from public.payment_receipts r
join public.payment_orders o
  on r.source_provider = 'mercado_pago'
 and r.source_reference = o.external_reference
where not exists (
  select 1 from public.payment_receipt_items i
  where i.receipt_id = r.id and i.line_no = 1
)
on conflict (receipt_id, line_no) do nothing;

insert into public.payment_receipts (
  source_provider, source_reference, source_payment_id, source_order_id,
  payment_status, receipt_status, amount, currency, paid_at,
  payment_method_id, payment_type_id, installments, live_mode, test_mode
)
select
  'mercado_pago_point', external_reference,
  coalesce(payment_reference_id, transaction_id), mp_order_id,
  status, case when status = 'refunded' then 'refunded' else 'issued' end,
  amount, currency, coalesce(paid_at, provider_updated_at, updated_at),
  payment_method_id, payment_method_type, installments, live_mode, test_mode
from public.mp_point_orders
where status in ('processed', 'refunded')
on conflict (source_provider, source_reference) do nothing;

insert into public.payment_receipt_items (
  receipt_id, line_no, item_code, label, quantity, unit_price, discount_amount, line_total
)
select r.id, 1, null, o.description, 1, o.amount, 0, o.amount
from public.payment_receipts r
join public.mp_point_orders o
  on r.source_provider = 'mercado_pago_point'
 and r.source_reference = o.external_reference
where not exists (
  select 1 from public.payment_receipt_items i
  where i.receipt_id = r.id and i.line_no = 1
)
on conflict (receipt_id, line_no) do nothing;
