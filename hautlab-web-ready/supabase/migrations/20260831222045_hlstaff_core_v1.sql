create table if not exists public.hlstaff_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  operator_key text unique references public.wa_operators(operator_key) on update cascade,
  display_name text not null,
  role text not null default 'staff' check (role in ('manager','staff')),
  base_monthly_salary numeric(12,2) not null default 0,
  commission_rate numeric(6,5) not null default 0.02,
  reactivation_rate numeric(6,5) not null default 0.01,
  active boolean not null default true,
  location_tracking_consent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.hlstaff_schedules (
  id bigint generated by default as identity primary key,
  staff_id uuid not null references public.hlstaff_profiles(id) on delete cascade,
  weekday smallint not null check (weekday between 1 and 7),
  scheduled_start time,
  scheduled_end time,
  grace_minutes integer not null default 5 check (grace_minutes between 0 and 120),
  active boolean not null default true,
  unique(staff_id, weekday)
);

create table if not exists public.hlstaff_shifts (
  id uuid primary key default gen_random_uuid(),
  staff_id uuid not null references public.hlstaff_profiles(id) on delete cascade,
  site_id uuid not null references public.hlstaff_sites(id),
  check_in_at timestamptz not null default now(),
  check_out_at timestamptz,
  check_in_lat double precision not null,
  check_in_lng double precision not null,
  check_in_accuracy_m double precision,
  check_out_lat double precision,
  check_out_lng double precision,
  check_out_accuracy_m double precision,
  check_in_distance_m double precision,
  check_out_distance_m double precision,
  check_in_status text not null default 'pending' check (check_in_status in ('inside','outside','pending')),
  check_out_status text check (check_out_status in ('inside','outside','pending')),
  minutes_late integer not null default 0,
  minutes_outside_geofence integer not null default 0,
  device_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists hlstaff_one_open_shift_per_staff on public.hlstaff_shifts(staff_id) where check_out_at is null;

create table if not exists public.hlstaff_location_events (
  id bigint generated by default as identity primary key,
  shift_id uuid not null references public.hlstaff_shifts(id) on delete cascade,
  staff_id uuid not null references public.hlstaff_profiles(id) on delete cascade,
  event_type text not null check (event_type in ('check_in','check_out','enter','exit','heartbeat','permission_denied','location_unavailable')),
  latitude double precision,
  longitude double precision,
  accuracy_m double precision,
  distance_m double precision,
  inside_geofence boolean,
  created_at timestamptz not null default now()
);
create index if not exists hlstaff_location_events_shift_created_idx on public.hlstaff_location_events(shift_id, created_at);

create table if not exists public.hlstaff_cash_payments (
  id uuid primary key default gen_random_uuid(),
  patient_name text not null,
  patient_phone text,
  conversation_id uuid references public.wa_conversations(id) on delete set null,
  amount numeric(12,2) not null check (amount > 0),
  concept text not null,
  revenue_owner text not null check (revenue_owner in ('karen','doctor','organic','referral')),
  commission_type text not null default 'none' check (commission_type in ('none','standard','reactivation')),
  commission_rate numeric(6,5) not null default 0,
  commission_amount numeric(12,2) generated always as (round(amount * commission_rate,2)) stored,
  captured_by uuid references public.hlstaff_profiles(id) on delete set null,
  paid_at timestamptz not null default now(),
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists hlstaff_cash_paid_at_idx on public.hlstaff_cash_payments(paid_at);

