  unique(site_id, closure_date)
);

create or replace function public.hlstaff_haversine_m(lat1 double precision, lon1 double precision, lat2 double precision, lon2 double precision)
returns double precision
language sql immutable strict as $$
  select 6371000 * 2 * asin(sqrt(
    power(sin(radians(lat2-lat1)/2),2) +
    cos(radians(lat1))*cos(radians(lat2))*power(sin(radians(lon2-lon1)/2),2)
  ));
$$;

create or replace function public.hlstaff_check_in(p_site_id uuid, p_lat double precision, p_lng double precision, p_accuracy_m double precision default null, p_device_id text default null)
returns public.hlstaff_shifts
language plpgsql security definer set search_path=public as $$
declare
  v_staff public.hlstaff_profiles;
  v_site public.hlstaff_sites;
  v_distance double precision;
  v_sched public.hlstaff_schedules;
  v_late integer := 0;
  v_shift public.hlstaff_shifts;
begin
  select * into v_staff from public.hlstaff_profiles where id=auth.uid() and active=true;
  if v_staff.id is null then raise exception 'STAFF_PROFILE_NOT_FOUND'; end if;
  select * into v_site from public.hlstaff_sites where id=p_site_id and active=true;
  if v_site.id is null then raise exception 'SITE_NOT_FOUND'; end if;
  if v_site.latitude is null or v_site.longitude is null then raise exception 'SITE_NOT_CALIBRATED'; end if;
  if exists(select 1 from public.hlstaff_shifts where staff_id=v_staff.id and check_out_at is null) then raise exception 'OPEN_SHIFT_EXISTS'; end if;
  v_distance := public.hlstaff_haversine_m(p_lat,p_lng,v_site.latitude,v_site.longitude);
  select * into v_sched from public.hlstaff_schedules where staff_id=v_staff.id and weekday=extract(isodow from timezone('America/Merida',now()))::int and active=true;
  if v_sched.id is not null and v_sched.scheduled_start is not null then
    v_late := greatest(0, floor(extract(epoch from ((timezone('America/Merida',now())::time) - v_sched.scheduled_start))/60)::int - v_sched.grace_minutes);
  end if;
  insert into public.hlstaff_shifts(staff_id,site_id,check_in_lat,check_in_lng,check_in_accuracy_m,check_in_distance_m,check_in_status,minutes_late,device_id)
  values(v_staff.id,v_site.id,p_lat,p_lng,p_accuracy_m,v_distance,case when v_distance <= v_site.radius_m then 'inside' else 'outside' end,v_late,p_device_id)
  returning * into v_shift;
  insert into public.hlstaff_location_events(shift_id,staff_id,event_type,latitude,longitude,accuracy_m,distance_m,inside_geofence)
  values(v_shift.id,v_staff.id,'check_in',p_lat,p_lng,p_accuracy_m,v_distance,v_distance <= v_site.radius_m);
  if v_distance > v_site.radius_m then raise exception 'OUTSIDE_GEOFENCE'; end if;
  return v_shift;
exception when others then
  if SQLERRM='OUTSIDE_GEOFENCE' then
    delete from public.hlstaff_shifts where id=v_shift.id;
  end if;
  raise;
end;
$$;

create or replace function public.hlstaff_check_out(p_lat double precision, p_lng double precision, p_accuracy_m double precision default null)
returns public.hlstaff_shifts
language plpgsql security definer set search_path=public as $$
declare
  v_staff public.hlstaff_profiles;
  v_shift public.hlstaff_shifts;
  v_site public.hlstaff_sites;
  v_distance double precision;
begin
  select * into v_staff from public.hlstaff_profiles where id=auth.uid() and active=true;
  if v_staff.id is null then raise exception 'STAFF_PROFILE_NOT_FOUND'; end if;
  select * into v_shift from public.hlstaff_shifts where staff_id=v_staff.id and check_out_at is null order by check_in_at desc limit 1 for update;
  if v_shift.id is null then raise exception 'NO_OPEN_SHIFT'; end if;
  select * into v_site from public.hlstaff_sites where id=v_shift.site_id;
  v_distance := public.hlstaff_haversine_m(p_lat,p_lng,v_site.latitude,v_site.longitude);
  update public.hlstaff_shifts set check_out_at=now(),check_out_lat=p_lat,check_out_lng=p_lng,check_out_accuracy_m=p_accuracy_m,check_out_distance_m=v_distance,check_out_status=case when v_distance <= v_site.radius_m then 'inside' else 'outside' end,updated_at=now() where id=v_shift.id returning * into v_shift;
  insert into public.hlstaff_location_events(shift_id,staff_id,event_type,latitude,longitude,accuracy_m,distance_m,inside_geofence)
  values(v_shift.id,v_staff.id,'check_out',p_lat,p_lng,p_accuracy_m,v_distance,v_distance <= v_site.radius_m);
  return v_shift;
end;
$$;

create or replace function public.hlstaff_log_location(p_shift_id uuid, p_event_type text, p_lat double precision, p_lng double precision, p_accuracy_m double precision default null)
returns void language plpgsql security definer set search_path=public as $$
declare v_staff public.hlstaff_profiles; v_shift public.hlstaff_shifts; v_site public.hlstaff_sites; v_distance double precision;
begin
 select * into v_staff from public.hlstaff_profiles where id=auth.uid() and active=true;
 select * into v_shift from public.hlstaff_shifts where id=p_shift_id and staff_id=v_staff.id and check_out_at is null;
 if v_shift.id is null then raise exception 'OPEN_SHIFT_NOT_FOUND'; end if;
 select * into v_site from public.hlstaff_sites where id=v_shift.site_id;
 v_distance := public.hlstaff_haversine_m(p_lat,p_lng,v_site.latitude,v_site.longitude);
 insert into public.hlstaff_location_events(shift_id,staff_id,event_type,latitude,longitude,accuracy_m,distance_m,inside_geofence)
 values(v_shift.id,v_staff.id,p_event_type,p_lat,p_lng,p_accuracy_m,v_distance,v_distance <= v_site.radius_m);
end; $$;

create or replace view public.hlstaff_revenue_summary_monthly as
select date_trunc('month', paid_at at time zone 'America/Merida')::date as month,
       revenue_owner,
       count(*) as payments,
       sum(amount)::numeric(14,2) as gross_revenue,
       sum(commission_amount)::numeric(14,2) as commission
from public.hlstaff_cash_payments
group by 1,2;

